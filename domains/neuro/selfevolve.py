"""Self-evolution: the agent picks its own opponents and builds its own curriculum.

No human-authored demos, and no hand-picked opponent ladder.  The pool starts
with random play plus frozen copies of the agent itself; every recorded game
updates a running win rate per opponent, and sampling prefers the ones sitting
on the frontier (win rate near 0.5, or where the win rate is moving fastest).
Each iteration mutates the frontier's gene to spawn a new opponent, so the
curriculum is generated by the learner rather than by us.

Three sampling rules are implemented:

* ``pfsp``     -- prioritized fictitious self-play: weight ∝ (1 - win)^beta.
                  Strong opponents get the frames, but not all of them.
* ``progress`` -- weight ∝ |Δ win rate|: play whoever teaches you the fastest,
                  which is the learning-progress variant of autocurricula.
* ``uniform``  -- the control arm.

``record`` is the only place the pool learns anything, so an abandoned or
broken opponent cannot poison the statistics.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Callable

import numpy as np

# Bounds for the scripted-opponent genome (see domains/duel/bot.py).  Keeping
# them here means a mutated gene can never leave the range the Bot understands.
GENE_BOUNDS = {
    "aggr": (0.0, 1.0),
    "guard": (0.0, 1.0),
    "kick": (0.0, 1.0),
    "dist": (0.8, 2.8),
    "react": (2, 18),
    "idle": (0.0, 0.5),
    "loot": (0.0, 0.5),
    "avoid": (0.0, 0.5),
}
GENE_WEAPONS = ("none", "shield", "twin", "polearm", "javelin")


@dataclass
class Entry:
    name: str
    make: Callable[[], Any]
    gene: dict | None = None
    win: float = 0.5          # running win rate of the learner against it
    games: int = 0
    prev: float = 0.5
    progress: float = 0.0     # |Δ win| on the last update
    origin: str = "fixed"     # random / self / evolved
    retired: bool = False


class SelfPlayPool:
    def __init__(self, beta: float = 2.0, alpha: float = 0.25,
                 max_size: int = 10, min_games: int = 3,
                 competence_floor: float = 0.10):
        self.beta = float(beta)
        self.alpha = float(alpha)
        self.max_size = int(max_size)
        self.min_games = int(min_games)
        # Opponents we have not beaten once are not a lesson, they are a wall.
        self.competence_floor = float(competence_floor)
        self.entries: list[Entry] = []

    # ------------------------------------------------------------- structure
    def add(self, name: str, make: Callable[[], Any], gene: dict | None = None,
            win: float = 0.5, origin: str = "fixed") -> Entry:
        if any(e.name == name for e in self.entries):
            raise ValueError("duplicate opponent name: %s" % name)
        entry = Entry(name=name, make=make, gene=gene, win=float(win),
                      prev=float(win), origin=origin)
        self.entries.append(entry)
        return entry

    def remove(self, name: str):
        self.entries = [e for e in self.entries if e.name != name]

    def get(self, name: str) -> Entry | None:
        for e in self.entries:
            if e.name == name:
                return e
        return None

    def __len__(self):
        return len(self.entries)

    # ---------------------------------------------------------------- stats
    def record(self, name: str, outcome: float):
        """Update the running win rate.  ``outcome`` is 1 / 0.5 / 0 for us."""
        e = self.get(name)
        if e is None:
            return
        e.games += 1
        e.prev = e.win
        e.win += self.alpha * (float(outcome) - e.win)
        e.progress = abs(e.win - e.prev)

    def frontier(self) -> Entry | None:
        """The opponent closest to a 50% win rate -- where the gradient is."""
        live = [e for e in self.entries if e.games >= self.min_games]
        if not live:
            return None
        return min(live, key=lambda e: abs(e.win - 0.5))

    def weights(self, mode: str = "pfsp") -> np.ndarray:
        w = np.ones(len(self.entries), dtype=np.float64)
        for i, e in enumerate(self.entries):
            if mode == "pfsp":
                # Too strong (win ~ 0) is nearly useless, too weak is noise.
                w[i] = max(1.0 - e.win, 0.06) ** self.beta
                # ...but a cold-started learner that loses every game gets
                # drowned by its own hardest opponents.  Down-weight the ones
                # it has never beaten instead of handing them all the frames.
                if (e.games >= self.min_games
                        and e.win < self.competence_floor):
                    w[i] *= 0.15
            elif mode == "progress":
                w[i] = 0.04 + 6.0 * e.progress + 1.0 / (1.0 + e.games)
            # Cold-start bonus: an unmeasured opponent must be played, or the
            # pool never learns whether it is worth keeping.
            if e.games < self.min_games:
                w[i] *= 3.0
        return w

    def sample(self, rng: np.random.Generator, mode: str = "pfsp") -> Entry:
        if not self.entries:
            raise ValueError("empty pool")
        w = self.weights(mode)
        p = w / w.sum()
        return self.entries[int(rng.choice(len(self.entries), p=p))]

    def prune(self, hard_floor: float = 0.02, easy_ceiling: int = 0):
        """Retire hopeless opponents but never the current frontier."""
        frontier = self.frontier()
        keep = []
        for e in self.entries:
            if e.origin == "random":
                keep.append(e)
                continue
            if e.games >= 8 and frontier is not None and e.name != frontier.name:
                if e.win <= hard_floor or (easy_ceiling and e.win >= easy_ceiling):
                    e.retired = True
                    continue
            keep.append(e)
        self.entries = keep
        self._cap()
        return [e.name for e in self.entries if e.retired]

    def _cap(self):
        if len(self.entries) <= self.max_size:
            return
        # Drop the oldest evolved entries first; keep the random anchor and
        # any self snapshots (they are the self-play signal).
        while len(self.entries) > self.max_size:
            victim = next((e for e in self.entries if e.origin == "evolved"),
                          self.entries[0])
            self.entries.remove(victim)

    def stats(self) -> dict:
        frontier = self.frontier()
        live = [e for e in self.entries]
        hardest = min(live, key=lambda e: e.win) if live else None
        return {
            "pool_size": len(self.entries),
            "pool_frontier": None if frontier is None else frontier.name,
            "pool_frontier_win": None if frontier is None else round(frontier.win, 3),
            "pool_hardest": None if hardest is None else hardest.name,
            "pool_hardest_win": None if hardest is None else round(hardest.win, 3),
            "pool_games": int(sum(e.games for e in self.entries)),
        }

    # -------------------------------------------------------------- resume
    def state_dict(self) -> dict:
        return {
            "mode": "selfplay",
            "entries": [{"name": e.name, "win": e.win, "games": e.games,
                         "gene": e.gene, "origin": e.origin,
                         "retired": e.retired} for e in self.entries],
        }

    def load_stats(self, state: dict | None):
        """Restore win rates by name; opponents themselves are rebuilt."""
        if not state:
            return
        for item in state.get("entries", []):
            e = self.get(item["name"])
            if e is None:
                continue
            e.win = float(item.get("win", e.win))
            e.prev = e.win
            e.games = int(item.get("games", 0))
            e.retired = bool(item.get("retired", False))


def random_gene(rng: np.random.Generator) -> dict:
    gene = {k: float(rng.uniform(lo, hi)) for k, (lo, hi) in GENE_BOUNDS.items()}
    gene["react"] = int(round(gene["react"]))
    gene["weapon"] = str(rng.choice(GENE_WEAPONS))
    return gene


def mutate_gene(gene: dict, rng: np.random.Generator, sigma: float = 0.20,
                weapon_p: float = 0.15) -> dict:
    """Gaussian mutation inside the bounds the Bot already understands."""
    out = dict(gene)
    for key, (lo, hi) in GENE_BOUNDS.items():
        cur = float(out.get(key, (lo + hi) * 0.5))
        step = float(rng.normal(0.0, sigma * (hi - lo)))
        out[key] = float(np.clip(cur + step, lo, hi))
    out["react"] = int(round(out["react"]))
    if rng.random() < weapon_p:
        out["weapon"] = str(rng.choice(GENE_WEAPONS))
    else:
        out["weapon"] = out.get("weapon", "none")
    return out
